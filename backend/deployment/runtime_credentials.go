package deployment

import (
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"io"
	"sort"
	"strings"

	"backend/llm"
	"backend/tools"
)

// RuntimeAPITokenEnvName is the fixed Secret key and process environment name
// used by the deployed runtime's inbound bearer authentication.
const RuntimeAPITokenEnvName = "RUNTIME_API_TOKEN"

const (
	runtimeAPITokenPrefix  = "afrt_"
	runtimeAPITokenEntropy = 32
)

// RuntimeCredentialPlan contains credential names only. It is safe to derive
// from an immutable bundle because no secret value enters the plan.
type RuntimeCredentialPlan struct {
	EnvNames []string
}

// PlanRuntimeCredentials calculates the smallest AgentFlow-owned credential
// set required to run every agent in one immutable deployment bundle.
func PlanRuntimeCredentials(bundle *Bundle) (RuntimeCredentialPlan, error) {
	if bundle == nil {
		return RuntimeCredentialPlan{}, errors.New("deployment: bundle is required for runtime credential planning")
	}
	if err := bundle.ValidateStatic(); err != nil {
		return RuntimeCredentialPlan{}, fmt.Errorf("deployment: plan runtime credentials: %w", err)
	}

	required := make(map[string]struct{})
	for _, configuredAgent := range bundle.Agents {
		envName, ok := llm.CredentialEnvName(configuredAgent.Provider)
		if !ok {
			return RuntimeCredentialPlan{}, fmt.Errorf(
				"deployment: agent %q uses unsupported provider %q",
				configuredAgent.ID,
				configuredAgent.Provider,
			)
		}
		required[envName] = struct{}{}
		for _, toolName := range configuredAgent.Tools {
			for _, toolEnvName := range tools.CredentialEnvNames(toolName) {
				required[toolEnvName] = struct{}{}
			}
		}
	}

	envNames := make([]string, 0, len(required))
	for envName := range required {
		envNames = append(envNames, envName)
	}
	sort.Strings(envNames)
	return RuntimeCredentialPlan{EnvNames: envNames}, nil
}

// NewRuntimeAPIToken creates a new deployment-runtime bearer token using the
// operating system cryptographic random source.
func NewRuntimeAPIToken() (string, error) {
	return newRuntimeAPIToken(rand.Reader)
}

func newRuntimeAPIToken(random io.Reader) (string, error) {
	if random == nil {
		return "", errors.New("deployment: runtime API token random source is required")
	}
	raw := make([]byte, runtimeAPITokenEntropy)
	if _, err := io.ReadFull(random, raw); err != nil {
		return "", fmt.Errorf("deployment: generate runtime API token: %w", err)
	}
	return runtimeAPITokenPrefix + base64.RawURLEncoding.EncodeToString(raw), nil
}

// ValidateRuntimeAPIToken verifies the structure and entropy length of a token
// previously generated by AgentFlow. It does not compare token identities.
func ValidateRuntimeAPIToken(token string) error {
	if strings.TrimSpace(token) != token || !strings.HasPrefix(token, runtimeAPITokenPrefix) {
		return errors.New("deployment: invalid runtime API token")
	}
	raw, err := base64.RawURLEncoding.DecodeString(strings.TrimPrefix(token, runtimeAPITokenPrefix))
	if err != nil || len(raw) != runtimeAPITokenEntropy {
		return errors.New("deployment: invalid runtime API token")
	}
	return nil
}
